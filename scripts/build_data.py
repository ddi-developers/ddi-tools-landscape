#!/usr/bin/env python3
"""Regenerate data.yml and guide.yml from structure.yml + the item files in
ITEM_DIRS, and the `groups` block in settings.yml.

Run after editing anything under tools/, members/, examples/, profiles/
or structure.yml:
    python3 scripts/build_data.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

# Directories holding one .yml file per landscape item.
ITEM_DIRS = ("tools", "members", "examples", "profiles")

# One landscape2 group (tab in the grid view) per item directory, in this
# order. A group holds every category its items appear in, via `category`
# or `second_path`.
GROUPS = (
    ("Tools", "tools"),
    ("Members", "members"),
    ("Profiles", "profiles"),
    ("Examples", "examples"),
)

GROUPS_BEGIN = "# BEGIN GENERATED GROUPS"
GROUPS_END = "# END GENERATED GROUPS"
GROUPS_NOTE = (
    "# Generated by scripts/build_data.py from the item directories — do not\n"
    "# edit between these markers.\n"
)

HEADER = """\
# DDI Tools Landscape 2 — proposed taxonomy
#
# This file is GENERATED by scripts/build_data.py — do not edit directly.
# Edit structure.yml (category/subcategory order) and the item files in
# tools/, members/, examples/ and profiles/ (one file per item) instead,
# then re-run the script.
#
# Primary categories describe what a tool does.
# second_path entries classify the same item by DDI standard/version without duplication.
# DDI-CDI, SDTL and XKOS are intentionally empty until supporting tools are added.
# The current queXML -> DDI Codebook 2.1 relationship is retained but marked for verification.
# DDI versions are no longer stored in summary_release_rate.
"""

GUIDE_HEADER = """\
# Landscape2 guide
#
# This file is GENERATED by scripts/build_data.py — do not edit directly.
# Category/subcategory introductions come from the optional `guide` field in
# structure.yml; each item's entry comes from its name, homepage_url and
# description in tools/, members/, examples/ or profiles/.
#
# Reference documentation: https://github.com/cncf/landscape2/blob/main/docs/config/guide.yml
"""


class _LiteralStr(str):
    """String dumped in YAML block literal style (|)."""


yaml.add_representer(
    _LiteralStr,
    lambda dumper, data: dumper.represent_scalar(
        "tag:yaml.org,2002:str", data, style="|"
    ),
)


def _one_line(text) -> str:
    return " ".join(str(text or "").split())


def _block(*paragraphs) -> _LiteralStr:
    return _LiteralStr("\n\n".join(p for p in paragraphs if p) + "\n")


# Words always written in full capitals in annotation labels.
UPPERCASE_WORDS = {"api", "ddi", "doi", "id", "isbn", "orcid", "uri", "url"}


def _annotation_label(key: str) -> str:
    """'institution_url' -> 'Institution URL'."""
    return " ".join(
        word.upper() if word.lower() in UPPERCASE_WORDS else word.capitalize()
        for word in key.split("_")
        if word
    )


def _annotation_value(value) -> str:
    if isinstance(value, (list, tuple)):
        return ", ".join(_one_line(v) for v in value if v)
    return _one_line(value)


def _description_with_annotations(item: dict) -> str:
    """Item description followed by one 'Label: value' paragraph per
    extra.annotations entry."""
    annotations = (item.get("extra") or {}).get("annotations") or {}
    paragraphs = [_one_line(item.get("description"))]
    for key, value in annotations.items():
        value = _annotation_value(value)
        if value:
            paragraphs.append(f"{_annotation_label(key)}: {value}")
    return "\n\n".join(p for p in paragraphs if p)


def _guide_item(item: dict) -> str:
    name = item["name"]
    if item.get("homepage_url"):
        name = f"[{name}]({item['homepage_url']})"
    description = _one_line(item.get("description"))
    return f"- **{name}**" + (f": {description}" if description else "")


def build_guide(structure: dict, categories: list) -> dict:
    """Guide sections mirror data.yml; empty sections are left out."""
    guide_categories = []
    for category, cat_data in zip(structure["categories"], categories):
        subcategories = []
        for subcategory, sub_data in zip(
            category["subcategories"], cat_data["subcategories"]
        ):
            intro = _one_line(subcategory.get("guide"))
            items = "\n".join(_guide_item(i) for i in sub_data["items"])
            if intro or items:
                subcategories.append(
                    {
                        "subcategory": subcategory["name"],
                        "content": _block(intro, items),
                    }
                )

        intro = _one_line(category.get("guide"))
        if not intro and not subcategories:
            continue
        entry = {"category": category["name"]}
        if intro:
            entry["content"] = _block(intro)
        if subcategories:
            entry["subcategories"] = subcategories
        guide_categories.append(entry)
    return {"categories": guide_categories}


def _item_categories(item: dict) -> set:
    categories = {item["category"]}
    for path in item.get("second_path") or []:
        categories.add(path.split("/")[0].strip())
    return categories


def build_groups(structure: dict, items_by_dir: dict) -> list:
    """Groups for settings.yml; categories follow the structure.yml order."""
    groups = []
    for name, directory in GROUPS:
        used = set().union(*map(_item_categories, items_by_dir[directory]))
        categories = [c["name"] for c in structure["categories"] if c["name"] in used]
        if categories:
            groups.append({"name": name, "alias": directory, "categories": categories})
    return groups


def write_groups(groups: list) -> None:
    """Replace (or append) the marker-delimited groups block in settings.yml,
    leaving the rest of the hand-edited file untouched."""
    path = ROOT / "settings.yml"
    text = path.read_text()
    block = (
        f"{GROUPS_BEGIN}\n{GROUPS_NOTE}"
        + yaml.dump({"groups": groups}, sort_keys=False, allow_unicode=True)
        + f"{GROUPS_END}\n"
    )
    if GROUPS_BEGIN in text:
        before, rest = text.split(GROUPS_BEGIN, 1)
        after = rest.split(GROUPS_END, 1)[1].lstrip("\n")
        text = before + block + after
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text)


def main() -> None:
    structure = yaml.safe_load((ROOT / "structure.yml").read_text())

    tool_files = sorted(p for d in ITEM_DIRS for p in (ROOT / d).glob("*.yml"))
    tools = [yaml.safe_load(p.read_text()) for p in tool_files]
    items_by_dir = {d: [] for d in ITEM_DIRS}
    for tool, path in zip(tools, tool_files):
        items_by_dir[path.parent.name].append(tool)

    for tool, path in zip(tools, tool_files):
        for required in ("category", "subcategory", "name"):
            if required not in tool:
                sys.exit(f"{path}: missing required field '{required}'")

    categories = []
    for category in structure["categories"]:
        cat_out = {"name": category["name"], "subcategories": []}
        for subcategory in category["subcategories"]:
            items = [
                t
                for t in tools
                if t["category"] == category["name"]
                and t["subcategory"] == subcategory["name"]
            ]
            items.sort(key=lambda t: (t.get("order", 0), t["name"]))

            clean_items = []
            for item in items:
                clean = {
                    k: v
                    for k, v in item.items()
                    if k not in ("category", "subcategory", "order")
                }
                clean_items.append(clean)

            cat_out["subcategories"].append(
                {"name": subcategory["name"], "items": clean_items}
            )
        categories.append(cat_out)

    seen = {(t["category"], t["subcategory"]) for t in tools}
    known = {
        (c["name"], s["name"])
        for c in structure["categories"]
        for s in c["subcategories"]
    }
    unknown = seen - known
    if unknown:
        sys.exit(f"Item files reference unknown category/subcategory pairs: {unknown}")

    # Built before the annotations are merged into the descriptions, so the
    # guide keeps the plain descriptions.
    guide = build_guide(structure, categories)

    for cat_out in categories:
        for sub_out in cat_out["subcategories"]:
            for item in sub_out["items"]:
                description = _description_with_annotations(item)
                if description:
                    item["description"] = (
                        _LiteralStr(description + "\n")
                        if "\n" in description
                        else description
                    )

    with (ROOT / "data.yml").open("w") as f:
        f.write(HEADER + "\n")
        yaml.dump(
            {"categories": categories},
            f,
            sort_keys=False,
            default_flow_style=False,
            allow_unicode=True,
            width=88,
        )

    with (ROOT / "guide.yml").open("w") as f:
        f.write(GUIDE_HEADER + "\n")
        yaml.dump(
            guide,
            f,
            sort_keys=False,
            default_flow_style=False,
            allow_unicode=True,
            width=1000,
        )

    write_groups(build_groups(structure, items_by_dir))

    print(
        f"Wrote data.yml, guide.yml and settings.yml groups from {len(tool_files)} item files",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
